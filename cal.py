def multiply(a,b):
    return a*b

def add(a,b):
    return a+b

def subtract(a,b):
    return a-b

def divide(a,b):
    return a/b

def mod(a,b):
    return a%b
def simple_interest(a,b,c):
    ans = (a*b*c)/100
    return ans

def total_amnt(a,b,c):
    ans1 = (a*b*c)/100
    return ans1+a
def exp(a,b):
    return a**b